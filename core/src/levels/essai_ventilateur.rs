//! Niveau d'essai « ventilateur » : une tour que l'on ne grimpe qu'au souffle du
//! ventilateur (carte 5.6 du plan de capture). Hors de la table `NIVEAUX`, il
//! n'existe QUE dans les tests et dans le build de QA (fonctionnalité
//! `debug_niveaux`, touche F4) ; en production il n'est pas compilé dans le
//! binaire, comme les autres niveaux d'essai.
//!
//! Le ventilateur se tient sur le toit du rez-de-chaussée (sa casette, socle,
//! repose sur le sol). Son courant (2 s de souffle, 2 s d'arrêt, annoncé comme
//! un éclair) porte Pépin d'un étage entier jusqu'au balcon du drapeau, qu'un
//! saut direct depuis le sol ne peut pas atteindre (18 tuiles au-dessus) :
//! c'est la mécanique du ventilateur que ce niveau teste.

